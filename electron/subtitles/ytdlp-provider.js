const { SubtitleProvider } = require('./provider-interface');
const youtubedl = require('youtube-dl-exec');
const fs = require('fs');
const path = require('path');
const os = require('os');

function parseVtt(vttContent) {
  const lines = vttContent.split('\n');
  const segments = [];
  let currentSegment = null;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line || line.startsWith('WEBVTT') || line.startsWith('Kind:') || line.startsWith('Language:')) {
      continue;
    }

    // Time matching: 00:00:05.159 --> 00:00:07.160
    const timeMatch = line.match(/(\d{2}:\d{2}:\d{2}\.\d{3}) --> (\d{2}:\d{2}:\d{2}\.\d{3})/);
    if (timeMatch) {
      if (currentSegment) {
        segments.push(currentSegment);
      }
      const parseTime = (timeStr) => {
        const [hours, minutes, rest] = timeStr.split(':');
        const [seconds, millis] = rest.split('.');
        return parseInt(hours) * 3600 + parseInt(minutes) * 60 + parseInt(seconds) + parseInt(millis) / 1000;
      };
      
      const start = parseTime(timeMatch[1]);
      const end = parseTime(timeMatch[2]);
      
      currentSegment = {
        start,
        duration: end - start,
        text: ''
      };
    } else if (currentSegment) {
      // Remove tags like <c> or <00:00:05.000>
      let textLine = line.replace(/<[^>]+>/g, '').trim();
      if (textLine && currentSegment.text.indexOf(textLine) === -1) {
          currentSegment.text += (currentSegment.text ? ' ' : '') + textLine;
      }
    }
  }

  if (currentSegment) {
    segments.push(currentSegment);
  }

  return segments;
}

class YtDlpProvider extends SubtitleProvider {
  get name() {
    return 'yt-dlp';
  }

  async getTranscript(videoId) {
    const url = `https://www.youtube.com/watch?v=${videoId}`;
    const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'ytdlp-subs-'));
    const outputPath = path.join(tmpDir, '%(id)s.%(ext)s');
    
    try {
      await youtubedl(url, {
        writeAutoSubs: true,
        skipDownload: true,
        subLangs: 'en',
        subFormat: 'vtt',
        paths: tmpDir,
        output: '%(id)s.%(ext)s'
      });

      const files = fs.readdirSync(tmpDir);
      const vttFile = files.find(f => f.endsWith('.vtt'));
      
      if (!vttFile) {
        throw new Error('No VTT file downloaded');
      }

      const vttContent = fs.readFileSync(path.join(tmpDir, vttFile), 'utf-8');
      const segments = parseVtt(vttContent);

      if (segments.length === 0) {
        throw new Error('Parsed VTT has no segments');
      }

      return {
        language: 'en',
        autoGenerated: true,
        segments
      };
    } catch (err) {
      throw new Error(`yt-dlp failed: ${err.message}`);
    } finally {
      fs.rmSync(tmpDir, { recursive: true, force: true });
    }
  }
}

module.exports = { YtDlpProvider };
