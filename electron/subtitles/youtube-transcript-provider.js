const { YoutubeTranscript } = require('youtube-transcript');
const { SubtitleProvider } = require('./provider-interface');

class YoutubeTranscriptProvider extends SubtitleProvider {
  get name() {
    return 'youtube-transcript';
  }

  async getTranscript(videoId) {
    try {
      const transcript = await YoutubeTranscript.fetchTranscript(videoId);
      
      if (!transcript || transcript.length === 0) {
        throw new Error('No transcript returned');
      }

      const segments = transcript.map(item => ({
        text: item.text,
        start: item.offset / 1000,
        duration: item.duration / 1000
      }));

      return {
        language: 'en', // This provider generally returns English by default or auto-detects, but doesn't easily expose the language
        autoGenerated: true,
        segments
      };
    } catch (err) {
      throw new Error(`youtube-transcript failed: ${err.message}`);
    }
  }
}

module.exports = { YoutubeTranscriptProvider };
