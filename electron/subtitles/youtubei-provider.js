const { Innertube } = require('youtubei.js');
const { SubtitleProvider } = require('./provider-interface');

class YoutubeIProvider extends SubtitleProvider {
  constructor() {
    super();
    this.ytPromise = Innertube.create();
  }

  get name() {
    return 'youtubei.js';
  }

  async getTranscript(videoId) {
    try {
      const yt = await this.ytPromise;
      const info = await yt.getInfo(videoId);
      
      const transcriptData = await info.getTranscript();
      if (!transcriptData || !transcriptData.transcript) {
        throw new Error('No transcript available from youtubei');
      }

      const segments = [];
      
      // Parse the transcript segments
      if (transcriptData.transcript.content?.body?.initial_segments) {
         for (const segment of transcriptData.transcript.content.body.initial_segments) {
             segments.push({
                 text: segment.snippet.text,
                 start: parseInt(segment.start_ms) / 1000,
                 duration: parseInt(segment.duration_ms) / 1000
             });
         }
      }

      if (segments.length === 0) {
        throw new Error('Parsed transcript has no segments');
      }

      return {
        language: 'en', // Can be enhanced later by inspecting available languages
        autoGenerated: true,
        segments
      };
    } catch (err) {
      throw new Error(`youtubei failed: ${err.message}`);
    }
  }
}

module.exports = { YoutubeIProvider };
